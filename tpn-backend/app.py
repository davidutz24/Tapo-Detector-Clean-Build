def api_delete_detection(id):
    if os.path.basename(id) != id or "/" in id or "\\" in id or not id.lower().endswith(".jpg"):
        abort(400)

    with detection_lock:
        existing = next((d for d in detections if d["id"] == id), None)
        if existing is None:
            abort(404)

        new_dets = [d for d in detections if d["id"] != id]
        detections.clear()
        detections.extend(new_dets)

    detection_dir_abs = os.path.abspath(DETECTION_DIR)
    fpath = os.path.abspath(os.path.join(detection_dir_abs, id))
    if os.path.commonpath([detection_dir_abs, fpath]) != detection_dir_abs:
        abort(400)
    if os.path.exists(fpath):
        try:
            os.remove(fpath)
        except Exception as e:
            log.error(f"Failed to delete {fpath}: {e}")
                
    return jsonify({"status": "ok"})

