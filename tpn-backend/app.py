@app.route("/api/brush-mask/<cam_id>", methods=["GET", "POST", "DELETE"])
def api_brush_mask(cam_id):
    path = brush_mask_path(cam_id)
    if request.method == "GET":
        if not os.path.exists(path):
            abort(404)
        mask = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
        if mask is None:
            abort(404)
        ok, png = cv2.imencode(".png", mask)
        if not ok:
            abort(500)
        return Response(png.tobytes(), mimetype="image/png")

    if request.method == "DELETE":
        if os.path.exists(path):
            os.remove(path)
        return jsonify({"status": "ok"})

    try:
        payload = request.get_json(silent=True) or {}
        mask = decode_mask_data_url(payload.get("mask"))
        if mask.size == 0:
            raise ValueError("Mask image is empty.")
        cv2.imwrite(path, mask)
        return jsonify({
            "status": "ok",
            "path": path,
            "width": int(mask.shape[1]),
            "height": int(mask.shape[0]),
        })
    except Exception as e:
        log.error(f"Failed to save brush mask for camera {cam_id}: {e}")
        return jsonify({"status": "error", "message": str(e)}), 500

