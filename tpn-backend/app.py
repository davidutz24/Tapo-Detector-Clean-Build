def decode_mask_data_url(data_url):
    if not isinstance(data_url, str) or "," not in data_url:
        raise ValueError("Mask image must be a data URL.")
    _, encoded = data_url.split(",", 1)
    raw = base64.b64decode(encoded)
    arr = np.frombuffer(raw, dtype=np.uint8)
    image = cv2.imdecode(arr, cv2.IMREAD_UNCHANGED)
    if image is None:
        raise ValueError("Mask image could not be decoded.")
    if image.ndim == 3:
        if image.shape[2] == 4:
            image = cv2.cvtColor(image, cv2.COLOR_BGRA2GRAY)
        else:
            image = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    return np.where(image >= 128, 255, 0).astype(np.uint8)


def validate_config(config):
    if not isinstance(config, dict):
        raise ValueError("Config must be a JSON object.")

    clean = dict(config)
    cameras = clean.get("cameras", [])
    if not isinstance(cameras, list):
        raise ValueError("Config cameras must be a list.")

    clean_cameras = []
    for idx, camera in enumerate(cameras):
        if not isinstance(camera, dict):
            continue
        cam_id = str(camera.get("id") or idx + 1)
        url = str(camera.get("url") or "").strip()
        if not url:
            continue
        clean_camera = dict(camera)
        clean_camera["id"] = cam_id
        clean_camera["name"] = str(camera.get("name") or f"Camera {cam_id}")
        clean_camera["url"] = url
        clean_camera["ignore_regions"] = validate_masks(camera.get("ignore_regions", []))
        clean_cameras.append(clean_camera)

    clean["cameras"] = clean_cameras
    return clean


def _derive_overall_status(statuses):
    if not statuses:
        return "stopped"
    if any(s == "running" for s in statuses):
        return "running"
    if any(s == "connecting" for s in statuses):
        return "connecting"
    if any(s == "error" for s in statuses):
        return "error"
    return "stopped"


def set_camera_state(stream_id, **updates):
    stream_id = str(stream_id)
    with detection_lock:
        state = camera_stats.setdefault(stream_id, {
            "id": stream_id,
            "name": f"Camera {stream_id}",
            "status": "stopped",
            "fps": 0,
            "last_frame": None,
            "last_error": None,
        })
        state.update(updates)

        camera_list = sorted(camera_stats.values(), key=lambda c: str(c.get("id", "")))
        stats["cameras"] = [dict(c) for c in camera_list]
        stats["status"] = _derive_overall_status([c.get("status", "stopped") for c in camera_list])
        fps_values = [float(c.get("fps", 0) or 0) for c in camera_list if c.get("status") == "running"]
        stats["fps"] = round(sum(fps_values) / len(fps_values), 1) if fps_values else 0


