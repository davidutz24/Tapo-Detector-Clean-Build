def validate_masks(masks):
    validated = []
    if not isinstance(masks, list):
        return validated
    for mask in masks:
        if not isinstance(mask, list) or len(mask) != 4:
            continue
        try:
            x, y, w, h = [float(v) for v in mask]
        except (TypeError, ValueError):
            continue
        x = max(0.0, min(1.0, x))
        y = max(0.0, min(1.0, y))
        w = max(0.0, min(1.0 - x, w))
        h = max(0.0, min(1.0 - y, h))
        if w > 0 and h > 0:
            validated.append([x, y, w, h])
    return validated


